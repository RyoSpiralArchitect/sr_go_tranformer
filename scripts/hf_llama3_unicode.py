"""Extract Llama Split classes from pinned Tokenizers, independent of Go Unicode.

Visits every Unicode scalar once per class. Writes the reference ranges and a
Go declaration block; paste the latter into monolith.go when updating the
explicit tokenizer profile. No model or network is used.
"""
import argparse
import json
from pathlib import Path

import tokenizers
from tokenizers import Regex, pre_tokenizers


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--go-output', type=Path, required=True)
    a = p.parse_args()
    if tokenizers.__version__ != '0.22.2':
        raise RuntimeError('Require tokenizers 0.22.2')
    scalars = ''.join(chr(r) for r in range(0x110000) if not 0xd800 <= r <= 0xdfff)
    classes = {}
    for name, pattern in (('Letter', r'\p{L}+'), ('Number', r'\p{N}+'), ('Space', r'\s+')):
        split = pre_tokenizers.Split(Regex(pattern), 'removed', invert=True)
        ranges = []
        for text, _ in split.pre_tokenize_str(scalars):
            lo, hi = ord(text[0]), ord(text[-1])
            if len(text) != hi-lo+1:
                raise RuntimeError('Non-contiguous scalar range')
            ranges.append([lo, hi])
        classes[name] = ranges
    a.output.write_text(json.dumps(dict(tokenizers=tokenizers.__version__, classes=classes),indent=2)+'\n')
    out = ['// Tokenizers 0.22.2 Split classes; generated by scripts/hf_llama3_unicode.py.',
           '// These tables deliberately do not follow the Go toolchain Unicode version.']
    for name, ranges in classes.items():
        out.append('var llama3'+name+'Ranges = [][2]rune{')
        for i in range(0,len(ranges),4):
            out.append('\t'+', '.join('{0x%x, 0x%x}' % tuple(r) for r in ranges[i:i+4])+',')
        out.append('}')
    a.go_output.write_text('\n'.join(out)+'\n')
    print({k:len(v) for k,v in classes.items()})


if __name__ == '__main__':
    main()
